function json(body, status = 200, extra = {}) {
  return new Response(JSON.stringify(body), {
    status,
    headers: { 'Content-Type': 'application/json', ...extra }
  });
}

// field -> { max length, label shown to the customer }
const FIELDS = {
  name:     { max: 100,  label: 'your name' },
  phone:    { max: 40,   label: 'a phone number' },
  email:    { max: 200,  label: 'an email address' },
  postcode: { max: 12,   label: 'a postcode' },
  service:  { max: 80,   label: 'the service you need', missing: 'Please choose the service you need.' },
  details:  { max: 4000, label: 'a short description of the work' }
};

// Deliberately loose. The job is to catch obvious mistakes (letters typed into
// the phone box, a postcode that is clearly not one) without rejecting valid
// entries: people write numbers with spaces, brackets, +44 prefixes, and a
// customer fumbling their own postcode should still be able to reach Sean.
const PHONE_OK = /^[0-9+()\s.-]{7,}$/;
const UK_POSTCODE_OK = /^[A-Z]{1,2}[0-9][A-Z0-9]?\s*[0-9][A-Z]{2}$/i;
const EMAIL_OK = /^[^@\s]+@[^@\s]+\.[^@\s]+$/;

/** Shared by the enquiry and EV survey forms. Returns null if the contact
 *  details look valid, otherwise { error, field } ready to send as JSON. */
function checkContact(c) {
  if (!EMAIL_OK.test(c.email)) {
    return { error: 'That email address does not look right. Please check it and try again.', field: 'email' };
  }
  if (!PHONE_OK.test(c.phone)) {
    return { error: 'That phone number does not look right. Please use digits only, for example 07700 900123.', field: 'phone' };
  }
  if (!UK_POSTCODE_OK.test(c.postcode)) {
    return { error: 'That postcode does not look right. Please check it, for example SY3 9NT.', field: 'postcode' };
  }
  return null;
}

async function handleEnquiry(request, env, ctx) {
  const limited = await checkRateLimit(request, env, 'enquiry');
  if (limited) return limited;

  let d;
  try {
    d = await request.json();
  } catch {
    return json({ error: 'Your enquiry did not arrive complete. Please try sending it again.' }, 400);
  }

  // Honeypot: bots fill every field, people leave this one alone.
  if (d.company) return json({ ok: true }, 200);

  if (failsTimeTrap(d.form_started)) return json({ ok: true }, 200);

  // Validation messages are written to be read by the customer and to name the
  // field, so a failed submission says what to fix instead of just failing.
  //
  // Field checks run BEFORE Turnstile on purpose. Turnstile tokens are single
  // use: checking it first spent the token on a submission that then failed
  // validation, so the customer's corrected retry was rejected as a failed
  // anti-spam check however right the form now was.
  const clean = {};
  for (const [field, { max, label, missing }] of Object.entries(FIELDS)) {
    const v = String(d[field] ?? '').trim();
    if (!v) return json({ error: missing || `Please enter ${label}.`, field }, 400);
    if (v.length > max) {
      return json({ error: `That ${label.replace(/^(your|an|a|the) /, '')} is too long. Please shorten it and try again.`, field }, 400);
    }
    clean[field] = v;
  }
  const bad = checkContact(clean);
  if (bad) return json(bad, 400);

  if (!(await verifyTurnstile(d['cf-turnstile-response'], env, request))) {
    return json({ error: 'The anti-spam check did not pass. Please tick the box again and resend.', turnstile: true }, 400);
  }

  const preferred = ['Phone', 'WhatsApp', 'Email'].includes(d.preferred) ? d.preferred : null;
  const id = crypto.randomUUID();

  if (!env.DB) return json({ error: 'Something went wrong at our end. Please call or WhatsApp Sean instead.' }, 500);

  try {
    await env.DB.prepare(
      `INSERT INTO enquiries (id, name, phone, email, postcode, service, details, preferred, ip_country)
       VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)`
    )
      .bind(
        id,
        clean.name,
        clean.phone,
        clean.email,
        clean.postcode,
        clean.service,
        clean.details,
        preferred,
        request.headers.get('cf-ipcountry') || null
      )
      .run();
  } catch (err) {
    return json({ error: 'Something went wrong at our end saving your enquiry. Please call or WhatsApp Sean instead.' }, 500);
  }

  // The enquiry is saved. Email is a notification, so send it after the
  // response goes out. A mail failure must never lose the enquiry.
  ctx.waitUntil(sendEmail(env, { id, ...clean, preferred }));

  return json({ ok: true }, 200);
}

async function sendEmail(env, r) {
  if (!env.RESEND_API_KEY || !env.TO_EMAIL || !env.FROM_EMAIL) return;

  const esc = (s) =>
    String(s ?? '').replace(/[<>&]/g, (ch) => ({ '<': '&lt;', '>': '&gt;', '&': '&amp;' }[ch]));

  const rows = [
    ['Name', r.name],
    ['Phone', r.phone],
    ['Email', r.email],
    ['Postcode', r.postcode],
    ['Service', r.service],
    ['Preferred contact', r.preferred || 'Not stated'],
    ['Details', r.details]
  ]
    .map(
      ([k, v]) =>
        `<tr><td style="padding:6px 14px 6px 0;vertical-align:top;color:#4B5B70">${esc(k)}</td>` +
        `<td style="padding:6px 0;vertical-align:top"><strong>${esc(v).replace(/\n/g, '<br>')}</strong></td></tr>`
    )
    .join('');

  const html = `
    <div style="font-family:-apple-system,Segoe UI,sans-serif;color:#011E3E;max-width:600px">
      <h2 style="margin:0 0 4px">New website enquiry</h2>
      <p style="margin:0 0 18px;color:#4B5B70">${esc(r.service)} in ${esc(r.postcode)}</p>
      <table style="border-collapse:collapse;font-size:15px">${rows}</table>
      <p style="margin-top:22px">
        <a href="tel:${esc(r.phone)}" style="background:#012F63;color:#fff;padding:10px 16px;border-radius:6px;text-decoration:none">Call ${esc(r.name)}</a>
      </p>
      <p style="color:#4B5B70;font-size:13px;margin-top:22px">Sent from swelectrical.co.uk. Also saved to the enquiry log.</p>
    </div>`;

  try {
    const res = await fetch('https://api.resend.com/emails', {
      method: 'POST',
      headers: {
        Authorization: `Bearer ${env.RESEND_API_KEY}`,
        'Content-Type': 'application/json'
      },
      body: JSON.stringify({
        from: env.FROM_EMAIL,
        to: [env.TO_EMAIL],
        reply_to: r.email,
        subject: `Website enquiry: ${r.service} (${r.postcode})`,
        html
      })
    });
    if (res.ok && env.DB) {
      await env.DB.prepare('UPDATE enquiries SET emailed = 1 WHERE id = ?').bind(r.id).run();
    }
  } catch {
    // Row stays with emailed = 0 so failures are visible in the log.
  }
}

async function listEnquiries(request, env) {
  if (!env.ADMIN_SECRET || request.headers.get('x-admin-secret') !== env.ADMIN_SECRET) {
    return json({ error: 'Unauthorised' }, 401);
  }
  if (!env.DB) return json({ error: 'Something went wrong at our end. Please call or WhatsApp Sean instead.' }, 500);

  const { results } = await env.DB.prepare(
    `SELECT id, created_at, name, phone, email, postcode, service, details,
            preferred, status, emailed
     FROM enquiries ORDER BY created_at DESC LIMIT 200`
  ).all();

  return json({ count: results.length, enquiries: results });
}

