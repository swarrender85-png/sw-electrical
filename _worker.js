/* Signed view links for survey media.
   Photos and video are never emailed as attachments — video in particular
   would be far too large. Instead the notification email links to each
   file, and the link is only valid because it carries a signature only
   this worker could have produced (using ADMIN_SECRET as the signing key)
   and an expiry a week out. There is no separate secret to configure. */

async function hmacHex(secret, message) {
  const key = await crypto.subtle.importKey(
    'raw', new TextEncoder().encode(secret),
    { name: 'HMAC', hash: 'SHA-256' }, false, ['sign']
  );
  const sig = await crypto.subtle.sign('HMAC', key, new TextEncoder().encode(message));
  return Array.from(new Uint8Array(sig)).map((b) => b.toString(16).padStart(2, '0')).join('');
}

async function signMediaKey(key, env) {
  const exp = Math.floor(Date.now() / 1000) + SURVEY_LINK_LIFETIME_SECONDS;
  const sig = await hmacHex(env.ADMIN_SECRET, `${key}:${exp}`);
  const params = new URLSearchParams({ key, exp: String(exp), sig });
  return `/api/survey-media?${params.toString()}`;
}

async function serveSurveyMedia(request, env) {
  const url = new URL(request.url);
  const key = url.searchParams.get('key');
  const exp = url.searchParams.get('exp');
  const sig = url.searchParams.get('sig');

  if (!key || !exp || !sig || !env.ADMIN_SECRET) {
    return new Response('Not found', { status: 404 });
  }
  if (Date.now() / 1000 > Number(exp)) {
    return new Response('This link has expired', { status: 410 });
  }

  const expected = await hmacHex(env.ADMIN_SECRET, `${key}:${exp}`);
  if (expected !== sig) {
    return new Response('Not found', { status: 404 });
  }

  if (!env.SURVEY_PHOTOS) return new Response('Not found', { status: 404 });

  // Range support matters most for video: without it, a player can't ask
  // for just the bytes it needs next, so it either has to buffer the whole
  // file before playing (choppy start, no seeking) or stalls repeatedly.
  // head() gets the size and content-type without pulling the file body.
  const head = await env.SURVEY_PHOTOS.head(key);
  if (!head) return new Response('Not found', { status: 404 });

  const headers = new Headers();
  head.writeHttpMetadata(headers);
  headers.set('accept-ranges', 'bytes');
  headers.set('cache-control', 'private, max-age=3600');
  if (!headers.get('content-type')) headers.set('content-type', 'application/octet-stream');

  const rangeHeader = request.headers.get('range');
  const rangeMatch = rangeHeader && /^bytes=(\d*)-(\d*)$/.exec(rangeHeader);

  if (rangeMatch) {
    const size = head.size;
    let start = rangeMatch[1] ? parseInt(rangeMatch[1], 10) : undefined;
    let end = rangeMatch[2] ? parseInt(rangeMatch[2], 10) : undefined;

    if (start === undefined) {
      // Suffix range, e.g. "bytes=-500" means the last 500 bytes.
      start = Math.max(size - end, 0);
      end = size - 1;
    } else if (end === undefined || end >= size) {
      end = size - 1;
    }

    if (start > end || start >= size) {
      headers.set('content-range', `bytes */${size}`);
      return new Response(null, { status: 416, headers });
    }

    const object = await env.SURVEY_PHOTOS.get(key, { range: { offset: start, length: end - start + 1 } });
    if (!object) return new Response('Not found', { status: 404 });

    headers.set('content-range', `bytes ${start}-${end}/${size}`);
    headers.set('content-length', String(end - start + 1));
    return new Response(object.body, { status: 206, headers });
  }

  const object = await env.SURVEY_PHOTOS.get(key);
  if (!object) return new Response('Not found', { status: 404 });
  headers.set('content-length', String(head.size));
  return new Response(object.body, { status: 200, headers });
}

async function sendSurveyEmail(env, r) {
  if (!env.RESEND_API_KEY || !env.TO_EMAIL || !env.FROM_EMAIL) return;

  const esc = (s) =>
    String(s ?? '').replace(/[<>&]/g, (ch) => ({ '<': '&lt;', '>': '&gt;', '&': '&amp;' }[ch]));

  const rows = [
    ['Name', r.name], ['Phone', r.phone], ['Email', r.email], ['Postcode', r.postcode],
    ['Property type', r.property_type], ['Tenure', r.tenure],
    ['Parking', r.parking_type], ['Preferred charger location', r.charger_location_notes],
    ['EV status', r.ev_status], ['Best time to call', r.preferred_time], ['Notes', r.notes]
  ]
    .filter(([, v]) => v)
    .map(
      ([k, v]) =>
        `<tr><td style="padding:6px 14px 6px 0;vertical-align:top;color:#4B5B70">${esc(k)}</td>` +
        `<td style="padding:6px 0;vertical-align:top"><strong>${esc(v).replace(/\n/g, '<br>')}</strong></td></tr>`
    )
    .join('');

  let mediaHtml = '<p style="color:#4B5B70">No photos or video were attached to this survey.</p>';
  if (r.media.length) {
    const SITE_ORIGIN = 'https://swelectrical.co.uk';
    const links = await Promise.all(
      r.media.map(async (m) => {
        const path = await signMediaKey(m.key, env);
        const verb = m.kind === 'video' ? 'Watch' : 'View';
        return `<li style="margin-bottom:6px"><a href="${SITE_ORIGIN}${path}">${verb} — ${esc(m.label)}</a></li>`;
      })
    );
    mediaHtml =
      '<p style="color:#4B5B70;margin-bottom:6px">Photos and video (links open directly, valid for 7 days):</p>' +
      `<ul style="padding-left:1.1rem;margin:0">${links.join('')}</ul>`;
  }

  const html = `
    <div style="font-family:-apple-system,Segoe UI,sans-serif;color:#011E3E;max-width:600px">
      <h2 style="margin:0 0 4px">EV charge point survey</h2>
      <p style="margin:0 0 18px;color:#4B5B70">${esc(r.postcode)}</p>
      <table style="border-collapse:collapse;font-size:15px">${rows}</table>
      <div style="margin-top:16px">${mediaHtml}</div>
      <p style="margin-top:22px">
        <a href="tel:${esc(r.phone)}" style="background:#012F63;color:#fff;padding:10px 16px;border-radius:6px;text-decoration:none">Call ${esc(r.name)}</a>
      </p>
      <p style="color:#4B5B70;font-size:13px;margin-top:22px">Sent from the EV survey on swelectrical.co.uk. Also saved to the survey log.</p>
    </div>`;

  try {
    const res = await fetch('https://api.resend.com/emails', {
      method: 'POST',
      headers: {
        Authorization: `Bearer ${env.RESEND_API_KEY}`,
        'Content-Type': 'application/json'
      },
      body: JSON.stringify({
        from: env.FROM_EMAIL,
        to: [env.TO_EMAIL],
        reply_to: r.email,
        subject: `EV survey: ${r.name} (${r.postcode})`,
        html
      })
    });
    if (res.ok && env.DB) {
      await env.DB.prepare('UPDATE ev_surveys SET emailed = 1 WHERE id = ?').bind(r.id).run();
    }
  } catch {
    // Row stays with emailed = 0 so failures are visible in the log.
  }
}
